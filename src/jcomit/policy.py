"""Build the OpenShell sandbox policy from the skills' declared access.

Default deny. The code is read-only, only data/ is writable, and the network
allows exactly what approved skills declared. Approving a skill is one flag:

  python -m jcomit.policy                         # approved skills only
  python -m jcomit.policy --allow share_report    # also let share_report out
  openshell policy set jcomit --policy policy.yaml --wait
"""

import argparse
import sys
from collections import defaultdict

from .skills import SKILLS, TOKEN_FACTORY, Access

PYTHON_BINARIES = (
    "/usr/bin/python3",
    "/usr/local/bin/python3",
    "/sandbox/.venv/bin/python3",
)

FILESYSTEM = """\
filesystem_policy:
  include_workdir: false
  read_only:
    - /usr
    - /lib
    - /proc
    - /dev/urandom
    - /etc
    - /app            # JComit code, baked into the image
    - /sandbox        # home: Python runtime and config
  read_write:
    - /sandbox/data   # statements, memory.db, outputs and the action log
    - /dev/null
"""

# Health checks list models; every approved skill also gets its own declared access.
BASELINE = (Access(TOKEN_FACTORY, "GET", "/v1/models"),)
NVIDIA_BACKUP = (
    Access("integrate.api.nvidia.com", "GET", "/v1/models"),
    Access("integrate.api.nvidia.com", "POST", "/v1/chat/completions"),
)


def section_name(host: str, skills: list[str]) -> str:
    if host == TOKEN_FACTORY:
        return "nebius_token_factory"
    if host == "integrate.api.nvidia.com":
        return "nvidia_backup"
    return "skill_" + "_".join(sorted(set(skills)))


def build(allow: set[str] = frozenset(), nvidia_backup: bool = False) -> str:
    unknown = allow - SKILLS.keys()
    if unknown:
        raise ValueError(f"unknown skill(s): {', '.join(sorted(unknown))}")

    rules: dict[str, set[tuple[str, str]]] = defaultdict(set)
    owners: dict[str, list[str]] = defaultdict(list)
    for a in BASELINE + (NVIDIA_BACKUP if nvidia_backup else ()):
        rules[a.host].add((a.method, a.path))
    for skill in SKILLS.values():
        if skill.approved or skill.name in allow:
            for a in skill.network:
                rules[a.host].add((a.method, a.path))
                owners[a.host].append(skill.name)

    out = [
        "# Generated by `python -m jcomit.policy`. Edit skills.py, not this file.",
        "version: 1",
        "",
        FILESYSTEM,
        "landlock:\n  compatibility: best_effort\n",
        "process:\n  run_as_user: sandbox\n  run_as_group: sandbox\n",
        "network_policies:",
    ]
    for host in sorted(rules):
        name = section_name(host, owners[host])
        out += [
            f"  {name}:",
            f"    name: {name}",
            f"    # used by: {', '.join(sorted(set(owners[host]))) or 'health checks'}",
            "    endpoints:",
            f"      - host: {host}",
            "        port: 443",
            "        protocol: rest",
            "        enforcement: enforce",
            "        rules:",
            *[f'          - allow: {{ method: {m}, path: "{p}" }}' for m, p in sorted(rules[host])],
            "    binaries:",
            *[f"      - {{ path: {b} }}" for b in PYTHON_BINARIES],
            "",
        ]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="jcomit.policy")
    p.add_argument("--allow", action="append", default=[], help="approve a skill that is off by default")
    p.add_argument("--nvidia-backup", action="store_true", help="also allow NVIDIA's hosted endpoint")
    p.add_argument("-o", "--output", help="write here instead of stdout")
    args = p.parse_args(argv)
    text = build(set(args.allow), args.nvidia_backup)
    if args.output:
        with open(args.output, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
